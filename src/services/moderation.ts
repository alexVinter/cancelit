/**
 * Модуль модерации контента.
 * Строго блокирует:
 * 1. Ссылки / URL (пользователь должен загружать скриншот или текст, а не ссылки).
 * 2. Политику (РФ, Россия, политики, партии, выборы, агитация, листовки, СВО, война, чиновники).
 * 3. Чернуху и 18+ (порно, интим, геи/ЛГБТ, насилие, расчлененка, кровь, трупы, наркотики, шок-контент).
 */

const BOUNDARY = '(?:^|[^а-яёa-z0-9])';
const END_BOUNDARY = '(?:$|[^а-яёa-z0-9])';

export const LINK_PATTERNS = [
  /https?:\/\/[^\s]+/i,
  /\bwww\.[^\s]+/i,
  /\b(?:t\.me|telegram\.me|instagram\.com|threads\.net|vk\.com|twitter\.com|x\.com|youtube\.com|youtu\.be|tiktok\.com|facebook\.com|fb\.watch|wildberries\.ru|ozon\.ru|avito\.ru|bit\.ly|clck\.ru|tinyurl\.com)\b/i,
  /\b[a-zA-Z0-9-]{2,}\.(?:ru|com|net|org|io|me|app|ai|co|xyz|by|kz|ua|su)\/[^\s]*/i
];

export function containsUrl(text: string): boolean {
  if (!text) return false;
  return LINK_PATTERNS.some(pattern => pattern.test(text));
}

export const POLITICAL_PATTERNS = [
  new RegExp(BOUNDARY + 'рф' + END_BOUNDARY, 'i'),
  /росси[яеиюей]|российск/i,
  /путин|медведев|мишустин|собянин|лавров|песков|навальн|пригожин/i,
  /госдум|совфед|совет\s+федераци|кремл|правительств\w*\s+рф/i,
  /депутат|губернатор|чиновник|сенатор|мэр\b/i,
  /партия|парти[июей]|единая\s+росси|кпрф|лдпр|новые\s+люди|справедливая\s+росси|яблоко/i,
  /выбор[ыа]|бюллетен|кандидат|предвыборн|голосовани|избирком|цик/i,
  /агитац|агитпоезд|агитбригад|листовк|прокламаци|политплакат/i,
  new RegExp(BOUNDARY + 'сво' + END_BOUNDARY, 'i'),
  /спецопераци|войн[аеуы]|мобилизаци|минобороны|военкомат|фронт[аеуы]?/i,
  /митинг|протест|пикет|оппозици|иноагент/i
];

export const CHERNUKHA_PATTERNS = [
  /порно|порнух|porn|эротик/i,
  /секс(?!аппил)|sex(?!y)|интим|минет|куннилингус|дилдо|пенис|вагин|шлюх|проститут|эрекц|оргазм/i,
  /гей[яеи]?|геев|геям|геях|лесби|лгбт|трансгендер|гомосексуал/i,
  new RegExp(BOUNDARY + 'член(?:а|у|ом|е|ы|ов)?' + END_BOUNDARY, 'i'),
  /труп|мертвец|расчленен|убийств|убивать|зарезать|застрелить/i,
  /изнасилован|насильник|педофил|зоофил|некрофил/i,
  /суицид|самоубийств|повесился|вскрыл\s+вены|спрыгнул\s+с\s+крыши/i,
  /кровищ|кишки|отрублен|пытать|пытка|казнь|обезглав/i,
  /наркотик|закладк|героин|кокаин|мефедрон|соли\b|марихуан|спайс/i,
  /теракт|террорист|шахид/i
];

export function checkContentModeration(text: string): { isAllowed: boolean; errorReason?: string } {
  if (!text || !text.trim()) {
    return { isAllowed: true };
  }

  // 1. Проверка на ссылки (URL)
  if (containsUrl(text)) {
    return {
      isAllowed: false,
      errorReason: 'По ссылкам не ходим. Закинь картинку или текст креатива'
    };
  }

  // 2. Проверка на политику
  for (const pattern of POLITICAL_PATTERNS) {
    if (pattern.test(text)) {
      return {
        isAllowed: false,
        errorReason: 'Политика строго запрещена правилами сервиса (всё, что связано с РФ, политиками, партиями, выборами, агитацией и листовками). Сервис работает исключительно с коммерческой рекламой брендов.'
      };
    }
  }

  // 3. Проверка на чернуху, 18+ и шок-контент
  for (const pattern of CHERNUKHA_PATTERNS) {
    if (pattern.test(text)) {
      return {
        isAllowed: false,
        errorReason: 'Шок-контент, 18+ и чернуха строго запрещены (порнография, насилие, ЛГБТ, наркотики, кровь, трупы). Сервис предназначен только для безопасного анализа коммерческой рекламы.'
      };
    }
  }

  return { isAllowed: true };
}
